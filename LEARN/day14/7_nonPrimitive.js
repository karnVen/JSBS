// Code snippet demonstrating primitive vs non-primitive data types

// This denotes a primitive data type
let str1 = "Los Angeles";
console.log(str1);            // Output: Los Angeles
console.log(typeof str1);     // Output: string

// This denotes a non-primitive data type
let stry = new String("California"); // Declaring a String object using the 'new' keyword
console.log(stry);            // Output: [String: 'California']
console.log(typeof stry);     // Output: object
